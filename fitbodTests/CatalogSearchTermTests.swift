//  The names people type for an exercise, each with the family it must find
//  in the first five results over the bundled catalog (RM-022). A miss is
//  fixed with an alias in the catalog, and a new miss joins this list.
//

import Foundation
import Testing
@testable import fitbod

@Suite("Catalog search terms")
struct CatalogSearchTermTests {

    /// The visible catalog as the Library searches it.
    private static func rows() throws -> [ExerciseSearch.Row] {
        try ExerciseCatalog.bundled().filter { !$0.isHidden }.map { entry in
            ExerciseSearch.Row(
                name: entry.name,
                family: entry.familyName,
                aliases: entry.aliasesJoined.split(separator: "|").map(String.init),
                brand: entry.brand,
                equipment: Equipment(rawValue: entry.equipmentRaw)?.displayName
            )
        }
    }

    /// The families in the first five results for `term`.
    private static func topFamilies(_ term: String, in rows: [ExerciseSearch.Row]) -> [String] {
        ExerciseSearch.results(term, in: rows) { $0 }.prefix(5).compactMap(\.item.family)
    }

    @Test("Every everyday name finds its family in the first five results")
    func everydayNames() throws {
        let rows = try Self.rows()
        let misses = Self.terms.filter { term, family in !Self.topFamilies(term, in: rows).contains(family) }
        #expect(misses.isEmpty, "\(misses.count) of \(Self.terms.count) terms miss: \(misses)")
    }

    @Test("Every family name and alias finds its family in the first five results")
    func catalogNames() throws {
        let rows = try Self.rows()
        var checks: [String: String] = [:]
        for row in rows {
            guard let family = row.family else { continue }
            for term in [family] + row.aliases where checks[term] == nil { checks[term] = family }
        }
        let misses = checks.filter { term, family in !Self.topFamilies(term, in: rows).contains(family) }
        #expect(misses.isEmpty, "\(misses.count) of \(checks.count) names miss: \(misses)")
    }

    @Test("A renamed row is found by its upstream name in the first five results")
    func upstreamNames() throws {
        let url = try #require(Bundle.main.url(forResource: "exercises", withExtension: "json"))
        let upstream = try JSONDecoder().decode([ExerciseDTO].self, from: Data(contentsOf: url))
        // A repeated ID is for `ExerciseCatalogTests` to report; here it must not crash the run.
        let listed = Dictionary(try ExerciseCatalog.bundled().filter { !$0.isHidden }.map { ($0.id, $0.name) }) { first, _ in first }
        let names = Set(listed.values.map { $0.lowercased() })
        let rows = try Self.rows()
        var misses: [String] = []
        for dto in upstream {
            // A name another row has now finds that row.
            guard let name = listed[dto.id], name != dto.name, !names.contains(dto.name.lowercased()) else { continue }
            let top = ExerciseSearch.results(dto.name, in: rows) { $0 }.prefix(5).map(\.item.name)
            if !top.contains(name) { misses.append("\(dto.name) → \(name)") }
        }
        #expect(misses.isEmpty, "\(misses.count) upstream names miss their row: \(misses)")
    }

