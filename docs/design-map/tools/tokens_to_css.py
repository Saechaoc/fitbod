#!/usr/bin/env python3
"""Writes mockups/bru-tokens.css from the app's own design tokens.

  python3 -I docs/design-map/tools/tokens_to_css.py
  python3 -I docs/design-map/tools/tokens_to_css.py --self-test

Colours come from the asset catalog, read by docs/design-system/tokens_check.py.
Type roles come from fitbod/Design/BRUFont.swift and measurements from
fitbod/Design/BRUMetrics.swift, so the mock-ups use the shipped values.
Rerun it whenever a token changes; never edit the CSS by hand.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "docs" / "design-system"))
from tokens_check import hex_of, load_tokens  # noqa: E402

FONT_SWIFT = ROOT / "fitbod" / "Design" / "BRUFont.swift"
METRICS_SWIFT = ROOT / "fitbod" / "Design" / "BRUMetrics.swift"
FONT_DIR = ROOT / "fitbod" / "Resources" / "Fonts"
OUT = ROOT / "docs" / "design-map" / "mockups" / "bru-tokens.css"
FONT_URL = "../../../fitbod/Resources/Fonts"  # FONT_DIR as seen from OUT

FACE = re.compile(r'^\s*case (\w+) = "([\w-]+)"', re.M)
ROLE = re.compile(r"((?:[ \t]*///[^\n]*\n)*)[ \t]*public static let (\w+): Font = \.bru\(\.(\w+), size: ([\d.]+)\)")
GROUP = re.compile(r"\n    public enum (\w+) \{(.*?)\n    \}", re.S)
METRIC = re.compile(r"public static let (\w+): CGFloat = ([\d.]+)")
TRACKING = re.compile(r"Tracking: ([+-]?[\d.]+)")


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def number(value: str) -> str:
    """A CSS length in px, written without a trailing .0."""
    return f"{float(value):g}px"


def faces(swift: str) -> dict[str, str]:
    """BRUFace case name -> PostScript name, which is also the TTF's name."""
    return dict(FACE.findall(swift))


def roles(swift: str, face_names: dict[str, str]) -> list[tuple[str, str, str, str, bool]]:
    """(role, PostScript face, size, tracking, uppercase) for each BRUFont role."""
    found = []
    for comment, role, face, size in ROLE.findall(swift):
        tracking = TRACKING.search(comment)
        upper = ".uppercase" in comment or face == "condensed"  # Bebas Neue reads as caps
        found.append((role, face_names[face], size, tracking.group(1) if tracking else "0", upper))
    return found


def metrics(swift: str) -> dict[str, str]:
    """CSS variable name -> px length, prefixed by the enum that holds it."""
    found = {}
    for group, body in GROUP.findall(swift):
        found |= {f"--bru-{kebab(group)}-{kebab(name)}": number(value) for name, value in METRIC.findall(body)}
        swift = swift.replace(body, "")
    found |= {f"--bru-{kebab(name)}": number(value) for name, value in METRIC.findall(swift)}
    return found


def css() -> str:
    face_names = faces(FONT_SWIFT.read_text())
    for postscript in face_names.values():
        if not (FONT_DIR / f"{postscript}.ttf").is_file():
            raise SystemExit(f"{postscript}.ttf is not in {FONT_DIR}")
    colours = {name: modes for name, modes in load_tokens().items() if name.startswith("bru")}

    def colour_block(selector: str, mode: str, indent: str = "") -> list[str]:
        lines = [f"{indent}{selector} {{"]
        lines += [f"{indent}  --{kebab(name)}: {hex_of(modes.get(mode, modes['light']))};"
                  for name, modes in colours.items()]
        return lines + [f"{indent}}}"]

    out = ["/* Generated by docs/design-map/tools/tokens_to_css.py from the app's tokens.",
           "   Do not edit; rerun the script. */", ""]
    for postscript in face_names.values():
        out.append(f'@font-face {{ font-family: "{postscript}"; '
                   f'src: url("{FONT_URL}/{postscript}.ttf") format("truetype"); }}')
    out += [""] + colour_block(":root", "light")[:-1]
    out += [f"  {name}: {value};" for name, value in metrics(METRICS_SWIFT.read_text()).items()] + ["}", ""]
    out += ["@media (prefers-color-scheme: dark) {"]
    out += colour_block(':root:not([data-theme="light"])', "dark", "  ") + ["}", ""]
    out += colour_block(':root[data-theme="dark"]', "dark") + [""]
    for role, postscript, size, tracking, upper in roles(FONT_SWIFT.read_text(), face_names):
        rule = f'font-family: "{postscript}", sans-serif; font-size: {number(size)}; letter-spacing: {number(tracking)};'
        out.append(f".bru-{kebab(role)} {{ {rule}{' text-transform: uppercase;' if upper else ''} }}")
    return "\n".join(out) + "\n"


def self_test() -> int:
    assert kebab("bruSignalOnInk") == "bru-signal-on-ink"
    assert number("1.5") == "1.5px" and number("44") == "44px" and number("-0.2") == "-0.2px"
    swift = ('public enum BRUFace: String {\n    case condensed = "BebasNeue-Regular"\n'
             '    case monoBold = "JetBrainsMono-Bold"\n}\n'
             "    /// Mono bold 13pt.\n    /// Tracking: +1.4 at call site. Case: .uppercase at call site.\n"
             "    public static let labelLarge: Font = .bru(.monoBold, size: 13)\n\n"
             "    /// 64pt condensed.\n    public static let condensedHero: Font = .bru(.condensed, size: 64)\n")
    names = faces(swift)
    assert names == {"condensed": "BebasNeue-Regular", "monoBold": "JetBrainsMono-Bold"}, names
    assert roles(swift, names) == [("labelLarge", "JetBrainsMono-Bold", "13", "+1.4", True),
                                   ("condensedHero", "BebasNeue-Regular", "64", "0", True)], roles(swift, names)
    swift = ("public enum BRUMetrics {\n    public enum Spacing {\n        public static let tight: CGFloat = 4\n    }\n"
             "    public static let touchTarget: CGFloat = 44\n}\n")
    assert metrics(swift) == {"--bru-spacing-tight": "4px", "--bru-touch-target": "44px"}, metrics(swift)
    print("self-test passed")
    return 0


def main() -> int:
    if sys.argv[1:] == ["--self-test"]:
        return self_test()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(css())
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
